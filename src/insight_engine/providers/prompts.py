"""Prompt library for the fixed insight-extraction schema."""

from __future__ import annotations

from insight_engine.models import SpeakerSegment

EXTRACTION_SYSTEM_PROMPT = """\
Ты — аналитик продуктовых интервью. Тебе дают транскрипт discovery-звонка с \
клиентом банка (реплики размечены спикерами и, если есть, таймкодами). Твоя \
задача — извлечь из реплик РЕСПОНДЕНТА (не интервьюера) все явные болевые \
точки, сформулированные строго по схеме.

Для каждой найденной боли верни объект со полями:
- "pain": короткий заголовок боли (5-12 слов)
- "context": когда/где возникает проблема
- "workaround": что респондент делает сейчас, чтобы обойти проблему (если не \
сказано явно — напиши "Не упомянуто")
- "jtbd": строго в формате "Когда [ситуация], я хочу [действие], чтобы \
[результат]"
- "quote": ТОЧНАЯ, дословная цитата из транскрипта (копия подстроки без \
изменений — по ней будет автоматический поиск в тексте, поэтому нельзя \
парафразировать, сокращать или менять пунктуацию)
- "signal_strength": "high" | "medium" | "low" — high, если респондент явно \
подчёркивает серьёзность/частоту проблемы; low, если это мимолётное замечание
- "speaker": имя/метка спикера, который произнёс цитату (как в транскрипте)

Верни ТОЛЬКО JSON-массив таких объектов, без пояснений и без markdown-разметки. \
Если болей нет — верни пустой массив [].
"""


def build_extraction_prompt(segments: list[SpeakerSegment]) -> str:
    lines = []
    for seg in segments:
        tc = f"[{_fmt(seg.start)}] " if seg.start is not None else ""
        lines.append(f"{tc}{seg.speaker}: {seg.text}")
    transcript = "\n".join(lines)
    return f"Транскрипт интервью:\n\n{transcript}\n\nИзвлеки болевые точки по схеме."


def _fmt(seconds: float | None) -> str:
    if seconds is None:
        return "00:00"
    m, s = divmod(int(seconds), 60)
    return f"{m:02d}:{s:02d}"


HYPOTHESIS_SYSTEM_PROMPT = """\
Ты — продакт-менеджер. Тебе дают кластер повторяющейся боли пользователей \
(заголовок боли + несколько цитат из разных интервью). Сформулируй ОДНУ \
гипотезу для бэклога строго в виде JSON-объекта с полями:
- "solution": конкретное продуктовое решение (короткая фраза)
- "metric": метрика, на которую повлияет решение
- "metric_direction": короткая фраза направления изменения, например \
"вырастет" или "снизится"
- "insight_summary": обобщение инсайта в одном предложении (без цитат)

Верни только JSON-объект, без пояснений.
"""


def build_hypothesis_prompt(pain_title: str, quotes: list[str]) -> str:
    quoted = "\n".join(f"- {q}" for q in quotes)
    return (
        f"Боль: {pain_title}\n\nЦитаты респондентов:\n{quoted}\n\n"
        "Сформулируй гипотезу по схеме."
    )
